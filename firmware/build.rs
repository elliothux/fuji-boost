use std::env;
use std::path::{Path, PathBuf};

const QUICKJS: &str = "../references/quickjs-rs/libquickjs-sys/embed/quickjs";
const POCKETJS: &str = "../references/pocketjs";
const QUICKJS_SOURCES: [&str; 5] = [
    "quickjs.c",
    "cutils.c",
    "libregexp.c",
    "libunicode.c",
    "dtoa.c",
];
const LIBC_SOURCES: [&str; 6] = [
    "malloc.c", "math.c", "stdio.c", "stdlib.c", "string.c", "time.c",
];

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    println!("cargo:rustc-link-arg=-T{}", root.join("link.ld").display());
    println!("cargo:rerun-if-changed=link.ld");
    println!("cargo:rerun-if-changed=src/start.S");
    protocol(&root);
    if env::var_os("CARGO_FEATURE_POCKET").is_some() {
        pocket(&root);
    }
}

/// `protocol.json` is the debug contract hosts read from the build manifest;
/// the firmware gets the same values as constants.
fn protocol(root: &Path) {
    use serde_json::Value;
    println!("cargo:rerun-if-changed=protocol.json");
    let text = std::fs::read_to_string(root.join("protocol.json")).unwrap();
    let protocol: Value = serde_json::from_str(&text).unwrap();
    let number = |value: &Value| -> u64 {
        match value {
            Value::Number(n) => n.as_u64().unwrap(),
            Value::String(s) => u64::from_str_radix(s.trim_start_matches("0x"), 16).unwrap(),
            _ => panic!("protocol.json: {value} is not a number"),
        }
    };
    let magic = |value: &Value| {
        let bytes = value.as_str().unwrap().as_bytes();
        assert_eq!(bytes.len(), 4, "protocol.json: magic must be 4 ASCII bytes");
        format!("u32::from_le_bytes(*b\"{}\")", value.as_str().unwrap())
    };
    let screaming = |name: &str| {
        let mut out = String::new();
        for c in name.chars() {
            if c.is_ascii_uppercase() {
                out.push('_');
            }
            out.extend(c.to_uppercase());
        }
        out.replace('-', "_")
    };
    let (log, mailbox, slot, scene) = (
        &protocol["log"],
        &protocol["mailbox"],
        &protocol["appSlot"],
        &protocol["scene"],
    );
    assert_eq!(
        slot["checksum"], "fnv1a32",
        "protocol.json: only fnv1a32 is implemented"
    );
    let mut out = String::from("// Generated by build.rs from firmware/protocol.json.\n");
    let mut constant = |name: &str, kind: &str, value: String| {
        out.push_str(&format!("pub const {name}: {kind} = {value};\n"));
    };
    constant(
        "LOG_BASE",
        "usize",
        format!("{:#x}", number(&log["address"])),
    );
    constant("LOG_SIZE", "usize", format!("{:#x}", number(&log["size"])));
    constant("LOG_MAGIC", "u32", magic(&log["magic"]));
    constant(
        "LOG_HEAD_WORD",
        "usize",
        number(&log["headWord"]).to_string(),
    );
    constant(
        "LOG_DATA_OFFSET",
        "usize",
        number(&log["dataOffset"]).to_string(),
    );
    constant(
        "MAILBOX_BASE",
        "usize",
        format!("{:#x}", number(&mailbox["address"])),
    );
    constant("MAILBOX_MAGIC", "u32", magic(&mailbox["magic"]));
    constant(
        "MAILBOX_VERSION",
        "u32",
        number(&mailbox["version"]).to_string(),
    );
    constant(
        "MAILBOX_FRAME_TICKS",
        "u64",
        number(&mailbox["frameTicks"]).to_string(),
    );
    for (index, word) in mailbox["words"].as_array().unwrap().iter().enumerate() {
        constant(
            &format!("W_{}", screaming(word.as_str().unwrap())),
            "usize",
            index.to_string(),
        );
    }
    for (name, string) in mailbox["strings"].as_object().unwrap() {
        let name = screaming(name);
        constant(
            &format!("W_{name}"),
            "usize",
            number(&string["word"]).to_string(),
        );
        constant(
            &format!("{name}_WORDS"),
            "usize",
            number(&string["words"]).to_string(),
        );
    }
    for (index, status) in mailbox["status"].as_array().unwrap().iter().enumerate() {
        constant(
            &format!("STATUS_{}", screaming(status.as_str().unwrap())),
            "u32",
            index.to_string(),
        );
    }
    constant(
        "WORK_RING_WORD",
        "usize",
        number(&mailbox["workRing"]["word"]).to_string(),
    );
    constant(
        "WORK_RING_LEN",
        "usize",
        number(&mailbox["workRing"]["length"]).to_string(),
    );
    constant(
        "APP_SLOT_BASE",
        "usize",
        format!("{:#x}", number(&slot["address"])),
    );
    constant(
        "APP_SLOT_SIZE",
        "usize",
        format!("{:#x}", number(&slot["size"])),
    );
    constant("APP_MAGIC", "u32", magic(&slot["magic"]));
    constant("APP_VERSION", "u32", number(&slot["version"]).to_string());
    constant(
        "APP_HEADER_BYTES",
        "usize",
        number(&slot["headerBytes"]).to_string(),
    );
    constant(
        "APP_PACK_ALIGN",
        "usize",
        number(&slot["packAlign"]).to_string(),
    );
    for (index, field) in slot["header"].as_array().unwrap().iter().enumerate() {
        constant(
            &format!("H_{}", screaming(field.as_str().unwrap())),
            "usize",
            index.to_string(),
        );
    }
    let reload = slot["reloadWord"].as_str().unwrap();
    constant("W_RELOAD", "usize", format!("W_{}", screaming(reload)));
    constant(
        "SCENE_BASE",
        "usize",
        format!("{:#x}", number(&scene["address"])),
    );
    constant(
        "SCENE_HEADER_BYTES",
        "usize",
        number(&scene["headerBytes"]).to_string(),
    );
    constant(
        "SCENE_MAX_WIDTH",
        "u32",
        number(&scene["maxWidth"]).to_string(),
    );
    constant(
        "SCENE_MAX_HEIGHT",
        "u32",
        number(&scene["maxHeight"]).to_string(),
    );
    constant("SCENE_MAGIC", "u32", magic(&scene["magic"]));
    for (index, field) in scene["header"].as_array().unwrap().iter().enumerate() {
        constant(
            &format!("S_{}", screaming(field.as_str().unwrap())),
            "usize",
            index.to_string(),
        );
    }
    let path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("protocol.rs");
    std::fs::write(path, out).unwrap();
}

fn required(name: &str) -> String {
    println!("cargo:rerun-if-env-changed={name}");
    env::var(name)
        .unwrap_or_else(|_| panic!("{name} is not set; build through `bun run firmware:build`"))
}

fn compiler(root: &Path) -> cc::Build {
    let llvm = env::var("FUJI_LLVM_BIN").unwrap_or_else(|_| "/opt/homebrew/opt/llvm@19/bin".into());
    println!("cargo:rerun-if-env-changed=FUJI_LLVM_BIN");
    println!("cargo:rerun-if-env-changed=FUJI_C_OPT");
    let mut build = cc::Build::new();
    build
        .compiler(Path::new(&llvm).join("clang"))
        .archiver(Path::new(&llvm).join("llvm-ar"))
        .no_default_flags(true)
        .warnings(false)
        .flag("--target=armv7a-none-eabihf")
        .flag("-mcpu=cortex-a7")
        .flag("-mfpu=neon-vfpv4")
        .flag("-mfloat-abi=hard")
        .flag("-marm")
        .flag("-mno-unaligned-access")
        .flag(format!(
            "-O{}",
            env::var("FUJI_C_OPT").unwrap_or_else(|_| "2".into())
        ))
        .flag("-ffunction-sections")
        .flag("-fdata-sections")
        .flag("-fno-common")
        .flag("-fno-strict-aliasing")
        .flag("-funsigned-char")
        .flag("-nostdlibinc")
        .flag("-Wno-implicit-function-declaration")
        .flag("-Wno-incompatible-pointer-types")
        .include(root.join("libc/include"))
        .include(root.join(QUICKJS))
        .define("_GNU_SOURCE", None)
        .define("CONFIG_VERSION", "\"2026-06-04\"");
    if env::var_os("FUJI_QUICKJS_NO_NAN_BOXING").is_some() {
        build.define("JS_NO_NAN_BOXING", None);
    }
    println!("cargo:rerun-if-env-changed=FUJI_QUICKJS_NO_NAN_BOXING");
    build
}

fn pocket(root: &Path) {
    let app_js = required("FUJI_APP_JS");
    let app_pak = required("FUJI_APP_PAK");
    let target = required("POCKETJS_TARGET_ID");
    let host_abi = required("POCKETJS_HOST_ABI");
    println!("cargo:rerun-if-changed={app_js}");
    println!("cargo:rerun-if-changed={app_pak}");
    println!("cargo:rerun-if-changed=libc");

    let mut quickjs = compiler(root);
    for source in QUICKJS_SOURCES {
        quickjs.file(root.join(QUICKJS).join(source));
    }
    quickjs.compile("fuji_quickjs");

    let mut libc = compiler(root);
    for source in LIBC_SOURCES {
        libc.file(root.join("libc/src").join(source));
    }
    libc.compile("fuji_libc");

    let pocketjs = root.join(POCKETJS);
    let runtime = pocketjs.join("engine/quickjs-c/pocket_runtime.c");
    println!("cargo:rerun-if-changed={}", runtime.display());
    compiler(root)
        .file(runtime)
        .include(pocketjs.join("engine/quickjs-c"))
        .include(pocketjs.join("engine/ui-cabi/include"))
        .include(pocketjs.join("contracts/generated"))
        .define("POCKETJS_TARGET_ID", format!("\"{target}\"").as_str())
        .define("POCKETJS_HOST_ABI", host_abi.as_str())
        .compile("fuji_pocket_runtime");
}
